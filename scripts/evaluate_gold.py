"""Score simple matching methods on the 780 pairs labelled one by one (gold/gold_pairs.csv).

    pip install duckdb pyarrow "dedupkit-br @ git+https://github.com/CaiqueDourado/DedupKit@v0.2.0#subdirectory=python"
    python scripts/evaluate_gold.py            # writes docs/gold-results.md

Every gold pair is a candidate that some blocking key produced (same barcode, same 2019 group,
same image, similar name, or refused in 2019), so the question for each method is: given this
candidate, is it the same product (same SKU)? Pairs labelled "unsure" are left out.
The silver labels of the dataset come from the "B2 build rules" row: compare methods against the
gold labels, not against the silver ones.
"""

from __future__ import annotations

import csv
import importlib.util
from pathlib import Path

import dedupkit_br as dk

ROOT = Path(__file__).resolve().parents[1]
spec = importlib.util.spec_from_file_location("build_pairs", ROOT / "scripts" / "build_pairs.py")
bp = importlib.util.module_from_spec(spec)
spec.loader.exec_module(bp)
CLF = bp.Classifier()


def build_rules(row) -> bool:
    if row["source"] == "refused_2019":
        return False
    return row["silver_label"] == "1"


METHODS = {
    "2019 catalog (merge every candidate except the refused ones)": lambda r: r["source"] != "refused_2019",
    "same normalized name": lambda r: dk.normalize(r["name_a"]) == dk.normalize(r["name_b"]),
    "same token key (words, singular, no stopwords)": lambda r: dk.token_key(r["name_a"]) == dk.token_key(r["name_b"]),
    "word overlap (Jaccard) >= 0.5": lambda r: bp.similarity(r["name_a"], r["name_b"]) >= 0.5,
    "DedupKit 0.2.0 checks (shared word + attributes)": lambda r: dk.shares_word(r["name_a"], r["name_b"]) and dk.conflict(r["name_a"], r["name_b"]) is None,
    "B2 build rules (DedupKit + model numbers; the silver labels)": build_rules,
}


def score(rows, fn):
    tp = fp = fn_ = tn = 0
    for r in rows:
        pred, gold = fn(r), r["label"] == "1"
        tp += pred and gold
        fp += pred and not gold
        fn_ += (not pred) and gold
        tn += (not pred) and not gold
    p = tp / (tp + fp) if tp + fp else 0.0
    rec = tp / (tp + fn_) if tp + fn_ else 0.0
    f1 = 2 * p * rec / (p + rec) if p + rec else 0.0
    return p, rec, f1, (tp + tn) / len(rows)


def main() -> None:
    rows = [r for r in csv.DictReader(open(ROOT / "gold" / "gold_pairs.csv", encoding="utf-8")) if r["label"] != ""]
    positives = sum(r["label"] == "1" for r in rows)
    lines = [
        "# Methods scored on the gold pairs",
        "",
        f"{len(rows)} pairs labelled one by one ({positives} same product, {len(rows) - positives} different; pairs marked unsure left out).",
        "Generated by `scripts/evaluate_gold.py`.",
        "",
        "| Method | Precision | Recall | F1 | Accuracy |",
        "|---|---:|---:|---:|---:|",
    ]
    for name, fn in METHODS.items():
        p, r, f1, acc = score(rows, fn)
        lines.append(f"| {name} | {p:.1%} | {r:.1%} | {f1:.3f} | {acc:.1%} |")
    lines += ["", "## Silver labels against gold, by pair type", "",
              "| Pair type | Gold pairs | Silver label agrees |", "|---|---:|---:|"]
    by_type = {}
    for r in rows:
        if r["pair_type"]:
            by_type.setdefault(r["pair_type"], []).append(r["silver_label"] == r["label"])
    for t in sorted(by_type):
        v = by_type[t]
        lines.append(f"| `{t}` | {len(v)} | {sum(v) / len(v):.0%} |")
    out = ROOT / "docs" / "gold-results.md"
    out.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
